-- Crea las 9 tablas del modelo entidad/relación (normalizado a 3FN).
--
-- EJECUTAR COMO: clubuach (F5 en SQL Developer)
-- Se puede volver a ejecutar: primero borra las tablas si ya existen.

-- Limpieza (orden inverso a las dependencias)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('CONSTANCIA','PAGO','PARTICIPACION_PROYECTO',
                                   'PROYECTO','ASISTENCIA','EVENTO',
                                   'TIPO_EVENTO','MIEMBRO','ROL')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
    FOR s IN (SELECT sequence_name FROM user_sequences
              WHERE sequence_name = 'SEQ_FOLIO_CONSTANCIA') LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;
END;
/

-- 1. ROL: puestos dentro del capítulo (presidente, tesorero, miembro...)
--    es_directiva = 1 indica que el rol forma parte de la mesa directiva
--    y por lo tanto entra al sistema como administrador.
CREATE TABLE rol (
    id_rol        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(50)  NOT NULL,
    descripcion   VARCHAR2(200),
    es_directiva  NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id_rol),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre),
    CONSTRAINT ck_rol_directiva CHECK (es_directiva IN (0, 1))
);

-- 2. MIEMBRO
CREATE TABLE miembro (
    id_miembro     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(60)  NOT NULL,
    apellidos      VARCHAR2(80)  NOT NULL,
    correo         VARCHAR2(120) NOT NULL,
    password_hash  VARCHAR2(255) NOT NULL,
    telefono       VARCHAR2(20),
    matricula      VARCHAR2(10)  NOT NULL,
    carrera        VARCHAR2(100) NOT NULL,
    semestre       NUMBER(2)     NOT NULL,
    fecha_ingreso  DATE DEFAULT SYSDATE NOT NULL,
    estatus        VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    id_rol         NUMBER NOT NULL,
    CONSTRAINT pk_miembro PRIMARY KEY (id_miembro),
    CONSTRAINT uq_miembro_correo UNIQUE (correo),
    CONSTRAINT uq_miembro_matricula UNIQUE (matricula),
    CONSTRAINT ck_miembro_semestre CHECK (semestre BETWEEN 1 AND 12),
    CONSTRAINT ck_miembro_estatus CHECK (estatus IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT fk_miembro_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol)
);

-- 3. TIPO_EVENTO: taller, plática, reunión, congreso...
CREATE TABLE tipo_evento (
    id_tipo_evento  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_tipo_evento PRIMARY KEY (id_tipo_evento),
    CONSTRAINT uq_tipo_evento_nombre UNIQUE (nombre)
);

-- 4. EVENTO: cada evento tiene un tipo y un miembro responsable.
--    Las horas se guardan como texto 'HH24:MI' (ej. '16:30').
CREATE TABLE evento (
    id_evento       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    titulo          VARCHAR2(120) NOT NULL,
    descripcion     VARCHAR2(500),
    fecha           DATE          NOT NULL,
    hora_inicio     VARCHAR2(5)   NOT NULL,
    hora_fin        VARCHAR2(5)   NOT NULL,
    lugar           VARCHAR2(120) NOT NULL,
    cupo            NUMBER(4)     NOT NULL,
    id_tipo_evento  NUMBER        NOT NULL,
    id_responsable  NUMBER        NOT NULL,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT ck_evento_cupo CHECK (cupo > 0),
    CONSTRAINT ck_evento_hora_ini CHECK (REGEXP_LIKE(hora_inicio, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT ck_evento_hora_fin CHECK (REGEXP_LIKE(hora_fin, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT ck_evento_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT fk_evento_tipo FOREIGN KEY (id_tipo_evento)
        REFERENCES tipo_evento (id_tipo_evento),
    CONSTRAINT fk_evento_responsable FOREIGN KEY (id_responsable)
        REFERENCES miembro (id_miembro)
);

-- 5. ASISTENCIA (tabla intermedia N:M entre miembro y evento)
--    REGISTRADO = se inscribió;  ASISTIO = sí llegó;  FALTO = no llegó
CREATE TABLE asistencia (
    id_asistencia   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_evento       NUMBER NOT NULL,
    id_miembro      NUMBER NOT NULL,
    fecha_registro  DATE DEFAULT SYSDATE NOT NULL,
    estatus         VARCHAR2(12) DEFAULT 'REGISTRADO' NOT NULL,
    CONSTRAINT pk_asistencia PRIMARY KEY (id_asistencia),
    CONSTRAINT uq_asistencia UNIQUE (id_evento, id_miembro),
    CONSTRAINT ck_asistencia_estatus CHECK (estatus IN ('REGISTRADO', 'ASISTIO', 'FALTO')),
    CONSTRAINT fk_asistencia_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento) ON DELETE CASCADE,
    CONSTRAINT fk_asistencia_miembro FOREIGN KEY (id_miembro)
        REFERENCES miembro (id_miembro)
);

-- 6. PROYECTO: cada proyecto tiene un miembro líder.
CREATE TABLE proyecto (
    id_proyecto   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    titulo        VARCHAR2(120) NOT NULL,
    descripcion   VARCHAR2(500),
    fecha_inicio  DATE NOT NULL,
    fecha_fin     DATE,
    estado        VARCHAR2(12) DEFAULT 'PLANEADO' NOT NULL,
    id_lider      NUMBER NOT NULL,
    CONSTRAINT pk_proyecto PRIMARY KEY (id_proyecto),
    CONSTRAINT ck_proyecto_estado CHECK (estado IN ('PLANEADO', 'EN_CURSO', 'TERMINADO', 'CANCELADO')),
    CONSTRAINT ck_proyecto_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT fk_proyecto_lider FOREIGN KEY (id_lider)
        REFERENCES miembro (id_miembro)
);

-- 7. PARTICIPACION_PROYECTO (tabla intermedia N:M miembro-proyecto)
CREATE TABLE participacion_proyecto (
    id_participacion  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_proyecto       NUMBER NOT NULL,
    id_miembro        NUMBER NOT NULL,
    funcion           VARCHAR2(80) NOT NULL,
    CONSTRAINT pk_participacion PRIMARY KEY (id_participacion),
    CONSTRAINT uq_participacion UNIQUE (id_proyecto, id_miembro),
    CONSTRAINT fk_participacion_proyecto FOREIGN KEY (id_proyecto)
        REFERENCES proyecto (id_proyecto) ON DELETE CASCADE,
    CONSTRAINT fk_participacion_miembro FOREIGN KEY (id_miembro)
        REFERENCES miembro (id_miembro)
);

-- 8. PAGO: cuotas y otros pagos de cada miembro.
CREATE TABLE pago (
    id_pago     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_miembro  NUMBER NOT NULL,
    concepto    VARCHAR2(100) NOT NULL,
    monto       NUMBER(8, 2)  NOT NULL,
    fecha_pago  DATE DEFAULT SYSDATE NOT NULL,
    metodo      VARCHAR2(15)  NOT NULL,
    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_metodo CHECK (metodo IN ('EFECTIVO', 'TRANSFERENCIA', 'TARJETA')),
    CONSTRAINT fk_pago_miembro FOREIGN KEY (id_miembro)
        REFERENCES miembro (id_miembro)
);

-- 9. CONSTANCIA: relación 1:1 con asistencia (id_asistencia es UNIQUE).
--    El folio lo genera el trigger trg_constancia_folio (archivo 04).
CREATE TABLE constancia (
    id_constancia  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_asistencia  NUMBER NOT NULL,
    folio          VARCHAR2(20) NOT NULL,
    fecha_emision  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_constancia PRIMARY KEY (id_constancia),
    CONSTRAINT uq_constancia_asistencia UNIQUE (id_asistencia),
    CONSTRAINT uq_constancia_folio UNIQUE (folio),
    CONSTRAINT fk_constancia_asistencia FOREIGN KEY (id_asistencia)
        REFERENCES asistencia (id_asistencia) ON DELETE CASCADE
);

-- Secuencia para los folios de constancia (CUACH-2026-00001, ...)
CREATE SEQUENCE seq_folio_constancia START WITH 1 INCREMENT BY 1 NOCACHE;

-- Índices sobre llaves foráneas que se consultan seguido
CREATE INDEX ix_miembro_rol          ON miembro (id_rol);
CREATE INDEX ix_evento_fecha         ON evento (fecha);
CREATE INDEX ix_evento_tipo          ON evento (id_tipo_evento);
CREATE INDEX ix_asistencia_miembro   ON asistencia (id_miembro);
CREATE INDEX ix_participacion_miem   ON participacion_proyecto (id_miembro);
CREATE INDEX ix_pago_miembro         ON pago (id_miembro);
